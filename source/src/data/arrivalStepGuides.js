export function arrivalStepGuide(route,index) {
  const step=route?.steps[index];
  if(!step)return null;
  const cue=ARRIVAL_STEP_GUIDES[route.placeId]?.[step.id]||step.guide;
  return {...cue,number:String(index+1).padStart(2,'0'),total:route.steps.length,
    direction:arrivalReferenceText(route,route.arrival==='parking'?step.instruction:(cue?.direction||step.instruction)),landmark:arrivalReferenceText(route,cue?.landmark||step.title),
    inspect:arrivalReferenceText(route,cue?.inspect||'보도 경계와 문 앞 바닥을 실제 사진에서 살펴봐요.'),
    next:route.steps[index+1]||null,connection:step.next||null,finish:route.finish};
}
